			  <p>
			  CTL Medical Corporation is delighted to announce that it has reached a national partnership agreement with G-21, an Italian-based biomaterials company. As a result, CTL Medical will now co-market G-21’s bone cement, kyphoplasty and vertebroplasty technologies in the United States.
</p><p>
“With the G-21 partnership, CTL Medical continues to fulfill its mission of becoming a fully integrated medical device design, development and manufacturing company serving the practice of spine surgery,” said Daniel Chon, president and CEO. “We intend to begin immediate distribution of the full line of acrylic-based bone cements for widespread procedures necessary for vertebrae consolidation and stabilization.”
</p>
 
