				<h4>Kyphoplasty:</h4>
				<p>
Osteoporosis and metastasis may weaken the vertebrae to such a point that they fracture by effect of the compression generated by normal everyday activities, causing pain and difficult of movement in the patients. kyphoplasty encourages restoration of the height of the vertebral body.  This is a minimally invasive percutaneous procedures whereby a balloon catheter is inserted into the vertebra to be treated through a channel created with a small–gauge cannula. The balloon is then filled with liquid containing the contrast medium in order to restore the height of the collapsed vertebral body bringing it back to its natural position. Once removed the balloon, in the created cavity, a specific bone cements with optimized radiopacity is injected in order to obtain the vertebral consolidation.
 </p>
<h4>CATHETERS WITH BALLOON FOR KYPHOPLASTY PROCEDURES</h4>
				<p>
Inflation of the kyphoplasty balloon creates a cavity and compacts cancellous bone in the vertebral body for delivering bone cement.  Low pre-inflation profile allows an accurate positioning inside the vertebral body through smaller diameter cannulas.  High quality manufacturing, range of shapes and sizes to fit patient anatomy.  Radiopaque markers allow for accurate visualization during positioning prior to inflation with contrast medium.
	</p>									

 
				<h4>Winch™ Kyphoplasty Balloons, 11 Gauge</h4>	<p>
The reduced diameter allows accurate placement even in small vertebral bodies and in the upper thoracic levels. Lower pre-inflation profile enables insertion into 10 gauge working cannulas. Exerted pressure up to 400 psi.
	</p>	
<i>Available in 15 and 20 mm length sizes.</i>
