CTL Medical Corp. received FDA clearance for its SEURAT Universal Pedicle Screw System.

Here are four notes.<br/>

1. The SEURAT Universal Pedicle Screw System is intended for spine fusion.<br/>

2. The system encompasses polyaxial and monoaxial; open and minimally invasive surgery; single and dual thread profile; solid and cannulated; and hex and hexalobe screws.<br/>

3. CTL Medical will launch the system in the second half of this year.<br/>

4. This clearance represents the second for CTL Medical in the first quarter of 2018.<br/>
