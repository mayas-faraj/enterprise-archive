                         <p>
                          <h4 class="title">State Safety Inspection checklist:</h4>     
                            Check for broken or burned out turn signals, brake lights, tail Lights, license plate light and 
                           reflectors
                           Check for missing or broken gas cap & seal
                           Check operation and condition of seat belts
                           Check parking brake function (does it holds the car)
                           Window Tint (1988 or newer only, check too dark/below AS1 line on front windshield)
                           Rear view mirror
                           Interior high beam indicator, high beam switch, turn signal indicators
                           Check wiper blade condition and operation
                           EGR, TAC, PCV components (present/working)
                           Check operation and condition of power steering and power brakes
                           Check EVAP cannister and air pump
                           Check operation and condition of headlights
                           Exhaust System (including manifold, check for leaks, proper hangers)
                           Check catalytic converter function (1984 or newer)
                           Check tires (rim condition, tire condition, minimum tire tread, all lug nuts, splits/cracks)
                           You must present proof of insurance at the time of inspection
                           during the driving portion of the State Inspection Test, the vehicle will be checked for steering slack or binding,horn operation,brake stopping distance and parking brake function.
                        </p>
                        <p>
                          <h4 class="title">Emissions Inspection checklist:</h4>     
                            Vehicles must be 2 to 24 years old and be gasoline powered
                            Vehicles built in 1995 or before must pass the ASM emissions test
                            Vehicles built in 1996 or later must pass the OBDII emissions test
                            *Insurance Limitations: 
                            Valid Limitations proof of insurance is required per state law.
                            Inspection fee is payable on pass or fail per state law.
                            Once an inspection has begun, it must be completed per state law.
                            State inspection fee varies from $7 to $25.50 for automobiles. Motorycycles, diesels and heavy trucks.
                        </p>
                        
                          <h4 class="title">Frequently Asked Questions</h4>
                           <h6>What happens if my vehicle fails the state inspection?</h6>                
                            <p>               
                            Whether your vehicle passes or fails the state inspection, state law requires that you pay 
                            the inspection fee. You will have 15 days from the date of the failure to get your car re-inspected at 
                            the same location for no charge. You will receive one free re-inspection only. If your vehicle passes, 
                            you will be given the sticker at no charge (be sure to save the rejection receipt you received when 
                            your vehicle failed). The vehicle will be completely re-inspected. If the vehicle fails a second time, 
                            you will have to pay the state fee the next time you try to get it inspected.
                        </p>
                            <h6>Can I make an appointment for a state inspection?</h6>                
                            <p>               
                            No. We are not allowed to take appointments for state inspections. State Inspections are 
                            performed on a first come, first served basis. During certain periods of the month, there may be a 
                            lengthy wait for state inspections. Generally, try to avoid the first and last 6 days of the month. 
                            Make sure you have a current insurance card to save time. We cannot call your insurance agent or 
                            receive faxes of your insurance card.
                        </p>
                        <p>You must present proof of insurance at the time of inspection
