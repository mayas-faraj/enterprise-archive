                        <h4 class="title">Drive Trains:</h4>
                        <P>Providing the Muscle for Your Car
                            The transmission, differentials and axles comprise the systems that turn the power that your engine generates into the force that turns your wheels. It is this system that puts the power to the pavement.
                        <br>
                        In other words, the harder you push the gas, the more power your engine generates, the more of that power is transferred to the wheels, and the faster you go.
                        <br>
                        The drive train contains two sets of gears: the transmission and the differential. The transmission adjusts the gear ratio, and the differential steps the power down again and turns the drive wheels at different speeds.
                        <br>
                        Between the engine and driving wheels of a vehicle is the transmission, a speed and power-changing device. Power comes from the engine into the transmission. This device “transmits” the power through a driveshaft to one of two axles, either front or rear. Some drive trains use a "transaxle," which is a combination of the transmission and the differential. While usually found on front wheel drive cars, these can also be used on mid- and rear-engine cars. For better weight balance, some cars have their engine in the front and the transaxle in the rear.<br>
                        If you have a 4x4, there is an extra piece to this puzzle called a transfer case. This device takes the shifted power from the transmission and then divides (transfers) it to the appropriate axles via a drive shaft front or rear.</P>
                        <h4 class="title">Transmissions to Power the Driveline</h4>
                        <p>There are two types of transmissions: manual and automatic. If you have a manual transmission, you have to shift the gears yourself using a gear shifter and clutch pedal in tandem.
                        <br>
                        With an automatic transmission, the gears shift themselves. This is done using a system that’s powered by hydraulic pressure. A shift valve controls each shift of the gears and shifts depending on speed, the road, and load conditions.</p>
                        <h4 class="title">Automatic Transmissions</h4>
                        <p>An automatic transmission is much easier to use. Unlike a manual transmission, you don't have to use a clutch pedal or gearshift lever. The automatic transmission does the work all by itself.
                        <br>
                        Immensely complex, at its simplest automatic transmissions automatically change to higher and lower gears with changes in the car's speed and the load on the engine. These also take into account the amount of pressure placed on the gas pedal, and shift accordingly to increase the engines RPM’s as necessary to reach the required speed.</p>
                        <h4 class="title">Automatic Transmission Essentials</h4>
                        <p>An automatic transmission consists of the following:</p>
                        <ul>
                        <li>Torque Converter</li>
                        <li>Brake Bands</li>
                        <li>Transmission Fluid</li>
                        </ul>
                        <h4 class="title">THE MANUAL TRANSMISSION</h4>
                        <p>Manual transmissions require the use of a clutch to apply and remove engine torque to the transmission input shaft. This happens gradually so that the car can be started from a complete stop.</p>
                        <p>The manual transmission encompasses a variety of active parts:</p>
                        <ul>
                            <li>Transmission Gears</li>
                            <li>Transmission Oil</li>
                            <li>Gear Shift Mechanism</li>
                            <li>The Clutch</li>
                            <li>The Clutch Plate</li>
                            <li>The Flywheel</li>
                            <li>The Clutch Pedal, Cables and Levers</li>
                            <li>Hydraulic Clutch</li>
                        </ul>
                        <h4 class="title">How Clutches Work</h4>
                        <p>The clutch on your car or truck can be compared to an on-off switch. When the clutch is disengaged 
                            (clutch pedal down), the release mechanism actuates the fork. The fork contacts the release bearing, 
                            moving it against the clutch diaphragm spring fingers. This action allows the clutch pressure plate to lift 
                            away from the flywheel, opening a very small space between the disc, flywheel and pressure plate. 
                            When the disc moves away from the flywheel, power flow from the engine to the transmission is 
                            interrupted. The engine crankshaft and flywheel are rotating at a higher speed than the disc and 
                            transmission input shaft that are coasting. When the clutch is engaged (clutch pedal up), the disc slips 
                            briefly to provide smooth engagement and, once again, the clutch clamps the disc against the flywheel. 
                            This causes the input shaft to turn, transmitting engine power to the transmission.</p>
